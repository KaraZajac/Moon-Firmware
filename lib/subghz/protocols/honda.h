#define SUBGHZ_PROTOCOL_HONDA_NAME "Honda V0"

/* ============================================================================
 * Honda KR5V2X (Civic 2016+ etc.) — FSK Manchester on 433 MHz
 *
 * Pandora firmware: Protocol.TX.FSK_Mode @ 0xA5F0
 *   Modulation: FSK (CC1101 reg 0x72 = 0x28 deviation)
 *   Encoding: Manchester (IEEE 802.3 / inverted convention)
 *     bit 1: LOW 500µs → HIGH 500µs  (rising edge)
 *     bit 0: HIGH 500µs → LOW 500µs  (falling edge)
 *   Bit order: MSB-first
 *   Preamble: 55 cycles × (HIGH 500µs + LOW 500µs), then LOW+HIGH extra
 *   Data: 112 bits (14 bytes) from buf[0..13], MSB-first
 *   Guard: LOW 3700µs before preamble
 *
 * When captured as OOK by Flipper's CC1101, the FSK signal is demodulated
 * with compressed timing. 500µs FSK → ~63µs in OOK capture (ratio ~8x).
 * The decoder works with these compressed timings from OOK captures.
 *
 * Frame layout (14 bytes = 112 bits, from Protocol_TX_Honda_Extended):
 *   buf[0]  = button | serial_hi_nibble
 *   buf[1]  = serial[23:16]
 *   buf[2]  = serial[15:8]
 *   buf[3]  = serial[7:0] / counter cascade byte
 *   buf[4]  = counter[23:16]
 *   buf[5]  = counter[19:12]
 *   buf[6]  = counter[11:4]
 *   buf[7]  = {mode_nibble[3:0], counter[3:0]}
 *   buf[8]  = checksum (table-substituted)
 *   buf[9]  = extra byte 1
 *   buf[10] = extra byte 2
 *   buf[11] = extra byte 3
 *   buf[12] = extra byte 4
 *   buf[13] = extra byte 5
 *
 * For decode/display we extract from the first 9 significant bytes.
 * The full 14-byte frame is preserved for re-transmission.
 * ==========================================================================*/

/* Timing constants for OOK-captured FSK Manchester */
#define HONDA_TE_SHORT        63u    /* half-bit duration in OOK capture */
#define HONDA_TE_LONG        126u    /* 2× half-bit (fused same-level halves) */
#define HONDA_TE_DELTA        25u
#define HONDA_GUARD_TIME_US  700u

/* Preamble */
#define HONDA_MIN_PREAMBLE_COUNT  20u
#define HONDA_PREAMBLE_CYCLES     55u   /* firmware: 55 cycles */

